// NOT PORTABLE. The registry in src/sanity/brandIcons.tsx draws every meaning
// with @sanity/icons; each meaning listed here is drawn instead as a tiny
// course cover, in the site's own cover colours, its meaning drawn only with
// the covers' own ornament shapes (a disc and half-moon make a teacher, the
// diagonal a pennant, the ring a coin, stripes lines of type; the Term Issue
// look: src/lib/cover.ts, CourseCover.astro). The files are generated by
// `node scripts/gen-studio-art.mjs` from the cover tokens in globals.css and
// shown exactly as drawn: artIcon() only places them in Sanity's 1em icon box.
//
// Which document type, field group or tool means what: brand/brand.config.json
// `studio.icons`. Meanings with no cover here (home, settings, contact, the
// Trash, the guide, redirects...) keep the starter's @sanity/icons line icons,
// which read better for the Studio's own furniture.
// =============================================================================

